"""Промпты PMAnalyze: релевантность+категория (1 запрос) и генерация ревью (markdown)."""

# 5 категорий по старой логике (папки -> колонка category)
CATEGORIES = [
    "Общие принципы",
    "Методики исследования",
    "PM-лог",
    "Проверка качества",
    "Без категории",
]


def build_relevance_prompt(title: str, abstract: str) -> str:
    """Оценка релевантности PM + определение категории одним JSON-ответом."""
    cats = ", ".join(f'"{c}"' for c in CATEGORIES)
    return f"""Оцени релевантность статьи для **Process Mining** по строгим критериям
и определи её категорию.

## Метаданные статьи:
Название: {title}
Аннотация: {abstract}

## ОСНОВНЫЕ КРИТЕРИИ РЕЛЕВАНТНОСТИ (каждый 0.0-1.0):
1. **Прямое упоминание PM**: process mining, discovery, conformance checking, enhancement,
   event logs, XES-формат, Celonis, UiPath, ProM
2. **Фокус на процессах**: бизнес-процессы, анализ логов событий, выявление отклонений,
   метрики (время, стоимость), операционные/оцифрованные процессы
3. **Практическое применение**: кейсы внедрения, этапы (сбор данных, анализ качества, мониторинг),
   ограничения (массовость, стандартизация)
4. **Качество и свежесть**: 2023-2026 гг., реальные примеры (финансы, логистика),
   инсайты (узкие места, ML), а не общие фразы

## ИСКЛЮЧЕНИЯ (все оценки 0.0):
- Нет связи с process mining (BI, RPA без конкретики)
- Спекуляции, устаревшие данные, неструктурированный текст

## КАТЕГОРИЯ (выбери РОВНО одну из списка):
[{cats}]
Правила выбора категории:
- "Общие принципы" — обзорные/концептуальные работы, теория process mining
- "Методики исследования" — новые алгоритмы/методы discovery, conformance, ML-подходы
- "PM-лог" — работа с event logs: извлечение, подготовка, XES, качество данных логов
- "Проверка качества" — conformance checking, аудит, соответствие, отклонения
- "Без категории" — если статья релевантна, но не попадает ни в одну группу, либо нерелевантна

## ПРАВИЛА:
- Факты ТОЛЬКО из текста метаданных
- Оценка с шагом 0.1: 0.0, 0.1, ..., 1.0
- overall_score = среднее по 4 критериям (округление до 0.1)
- is_relevant = true только если overall_score >= 0.6
- Если is_relevant = false, category = "Без категории"

## СТРОГО JSON (без markdown-обёртки, без комментариев):
{{
  "criterion_1": 0.8,
  "criterion_2": 0.7,
  "criterion_3": 0.6,
  "criterion_4": 0.9,
  "overall_score": 0.8,
  "is_relevant": true,
  "category": "Методики исследования",
  "reasoning": "Кратко: 1-упомянут Celonis; 2-event logs; 3-кейс банка..."
}}"""


def build_review_prompt(filename: str, pdf_url: str, pdf_text: str) -> str:
    """Генерация ревью в markdown по шаблону-саммари."""
    system = f"""Твоя задача: прочитать текст статьи из "{filename}", извлечь и адаптировать информацию для русскоязычного эксперта.

## ПРАВИЛА (строго соблюдай):
1. Переводи для русскоязычного эксперта, сохраняя академический стиль, сохраняй точные термины в оригинале, например 'process mining' или названия инструментов: 'SOUP: Simplifying Event...' оставляй как есть в оригинале
2. Факты БЕРИ ТОЛЬКО ИЗ ТЕКСТА, без домыслов
3. Первый раз термин сокращенно: на original языке. Далее: термин на оригинальном языке, перевод и расшифровки на русском
4. Алгоритмы - пошагово с оригинальными названиями
5. GitHub: найди в тексте ИЛИ проанализируй авторов/метод, иначе 'отсутствует'
6. Выводи результат строго по шаблону, без дополнительных комментариев и пояснений
7. Не меняй порядок пунктов шаблона и не добавляй новые
8. Не переводи авторов, оставляй в оригинале
9. Cсылка на источник: {pdf_url}. Подставь её в шаблон
10. Не используй заголовки для номерованных списков после описания

ПРИМЕР шаблона саммари:
- *Название статьи на русском*: [ТВОЙ ПЕРЕВОД];
- *Название оригинальной статьи на английском*: [ПОДСТАВЬ ОРИГИНАЛ];
- *Авторы на английском (в оригинале)*: [АВТОРЫ ИЗ СТАТЬИ];
- *Ссылка на источник статьи*: [ССЫЛКА, ИЗ ПУНКТА]

## Описание:
1. **Цель:** ...
2. **Проблема:** ...
3. **Задачи:** ...
4. **Подход - суть алгоритма/метода:** ...
5. **Как реализуется подход:** ...
6. **Пример из статьи:** ...
7. **Вывод:** ...

## Текст статьи из PDF:
{pdf_text}"""
    return system
