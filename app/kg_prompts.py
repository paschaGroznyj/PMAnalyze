"""Промпты Knowledge Graph для PMAnalyze.

Пайплайн знаний по паттерну LLM Wiki (Карпати): Ingest -> Relate -> Synthesize -> Lint.
Работает поверх схемы process_mining:
  - knowledge         (узлы: атомарные факты)
  - entity_relations  (рёбра: типизированные связи между узлами)
  - wiki_pages        (слой синтеза: markdown-страницы из группы узлов)
  - knowledge_review  (инкубатор: кандидаты на удаление/деградацию)

Все промпты возвращают строгий JSON без markdown-обёртки, чтобы pipeline мог
распарсить ответ напрямую.
"""

# Разрешённый словарь типов связей (эмуляция enum на уровне промпта).
# Совпадает с фактическими relation_type в графе — модель не должна изобретать новые.
RELATION_TYPES = [
    "relates_to",     # общая тематическая связь, дефолт
    "extends",        # B расширяет/развивает A
    "based_on",       # A построено на основе B
    "uses",           # A использует B (инструмент/метод)
    "includes",       # A включает B как часть
    "alternative_to", # A — альтернатива B
    "describes",      # A описывает B
    "evaluates",      # A оценивает/тестирует B
    "determines",     # A определяет/задаёт B
    "summarizes",     # A суммирует B
]

# Статусы узла знания (жизненный цикл)
KNOWLEDGE_STATUSES = ["active", "stale", "review", "archived"]


# ============================================================
# 1. INGEST — извлечение атомарного знания из сырого текста
# ============================================================
def build_knowledge_extraction_prompt(source_text: str, source_meta: str = "") -> str:
    """Из статьи/ревью/фрагмента вытащить набор АТОМАРНЫХ фактов-узлов.

    Атом = один самодостаточный факт, понятный без контекста источника.
    Результат -> кандидаты на INSERT в process_mining.knowledge.
    """
    meta_block = f"\n## Метаданные источника:\n{source_meta}\n" if source_meta else ""
    types = ", ".join(f'"{t}"' for t in KNOWLEDGE_STATUSES)
    return f"""Ты — экстрактор знаний для графа Process Mining.
Твоя задача: выделить из текста ЗНАЧИМЫЕ САМОДОСТАТОЧНЫЕ ТЕЗИСЫ (узлы графа знаний).

## ЧТО ТАКОЕ АТОМ (важно, не путать с "одно предложение"):
Атом = один связный ТЕЗИС, раскрывающий ОДНУ идею целиком. Тезис может состоять
из 2–5 предложений, если они вместе образуют завершённую мысль
(определение + условие + следствие; метод + для чего + как работает).
Атом — это НЕ обрывок предложения и НЕ строка из таблицы.

## ГЛАВНОЕ ПРАВИЛО ПРОТИВ ДРОБЛЕНИЯ:
Однородные факты ОБЪЕДИНЯЙ в ОДИН атом, а не плоди по штуке:
- перечни, наборы шагов процедуры, таблицы результатов, списки условий/классов,
  результаты сложности по разным классам, наборы метрик — это ОДИН атом
  со структурой ВНУТРИ поля text_knowledge (можно списком через "; " или "- ").
Пример ПЛОХО (дробление): 5 атомов вида
  "задача alignments NP-полна на process trees", "...NP-полна на T-systems", ...
Пример ХОРОШО (один атом):
  "Вычислительная сложность задачи alignments зависит от класса модели:
   PSPACE-полна на safe/sound workflow nets; NP-полна на process trees,
   T-systems и acyclic systems."

## ПРАВИЛА:
1. Каждый атом самодостаточен — понятен БЕЗ исходного текста.
2. Никаких местоимений-отсылок ("это", "он", "данный подход") — раскрывай явно.
3. Факты ТОЛЬКО из текста, без домыслов и обобщений.
4. Термины process mining, conformance checking, discovery, названия инструментов
   (Celonis, ProM, UiPath) — оставляй в оригинале.
5. Отбрасывай воду, маркетинг, повторы. Один и тот же факт не дублируй.
6. НИЖНЯЯ ГРАНИЦА СОДЕРЖАТЕЛЬНОСТИ: атом должен нести завершённую мысль.
   Обрывки-огрызки короче ~120 символов без законченного смысла ЗАПРЕЩЕНЫ —
   либо дополни контекстом, либо влей в соседний однородный атом.
7. КОЛИЧЕСТВО: столько атомов, сколько в тексте РАЗНЫХ идей. Лучше меньше,
   но плотнее и связнее. Ориентир — 3–8 атомов на статью, не дроби ради числа.
   Если значимых фактов нет — верни пустой массив.
8. Каждому атому дай importance 0.0-1.0: насколько факт ценен для базы знаний PM
   (0.9 = фундаментальный принцип/метод, 0.3 = частная деталь).
{meta_block}
## ВХОДНОЙ ТЕКСТ:
{source_text}

## СТРОГО JSON (без markdown-обёртки, без комментариев):
{{
  "atoms": [
    {{
      "text_knowledge": "Самодостаточная формулировка факта на русском.",
      "importance": 0.8,
      "status": "active",
      "tags": ["discovery", "event-log"]
    }}
  ]
}}
Допустимые status: [{types}]. По умолчанию "active"."""


# ============================================================
# 2. RELATE — построение типизированных рёбер между узлами
# ============================================================
def build_relation_inference_prompt(nodes_json: str) -> str:
    """На вход — список узлов знания (id + текст). На выход — рёбра графа.

    Результат -> кандидаты на INSERT в process_mining.entity_relations.
    """
    types = ", ".join(f'"{t}"' for t in RELATION_TYPES)
    return f"""Ты — построитель графа знаний Process Mining.
На вход даны узлы (атомарные факты) с их id. Найди СМЫСЛОВЫЕ связи между ними.

## УЗЛЫ (id + текст):
{nodes_json}

## ПРАВИЛА ПОСТРОЕНИЯ РЁБЕР:
1. Ребро направленное: source_id -> target_id. Направление важно (см. семантику типов).
2. relation_type выбирай РОВНО из словаря — новые типы изобретать ЗАПРЕЩЕНО:
   [{types}]
   Семантика:
   - relates_to     — общая тематическая связь (используй, если ничего точнее не подходит)
   - extends        — target развивает/расширяет source
   - based_on       — source построен на основе target
   - uses           — source использует target (метод/инструмент)
   - includes       — source включает target как часть
   - alternative_to — source и target — взаимозаменяемые альтернативы
   - describes      — source описывает target
   - evaluates      — source оценивает/тестирует target
   - determines     — source определяет/задаёт target
   - summarizes     — source суммирует target
3. Только НЕтривиальные связи. Не связывай всё со всем.
4. relevance_score 0.0-1.0 — насколько связь уверенная и осмысленная.
5. importance 0.0-1.0 — насколько связь важна для навигации по графу.
6. Не дублируй ребро в обе стороны, если тип уже отражает направление.
7. Если осмысленных связей нет — верни пустой массив.

## СТРОГО JSON (без markdown-обёртки):
{{
  "relations": [
    {{
      "source_id": 22,
      "target_id": 23,
      "relation_type": "extends",
      "relevance_score": 0.9,
      "importance": 0.8,
      "reasoning": "Кратко почему именно этот тип и направление."
    }}
  ]
}}"""


# ============================================================
# 2b. CROSS-LINK — связи нового узла с кандидатами из графа
# ============================================================
def build_cross_link_prompt(new_node_json: str, candidates_json: str) -> str:
    """Pairwise-инференс: один НОВЫЙ узел против набора КАНДИДАТОВ из графа.

    В отличие от build_relation_inference_prompt (общий пул узлов), тут LLM
    обязан оценить связь между узлом A (новый) и КАЖДЫМ кандидатом B по
    отдельности. Это не даёт модели распыляться на intra-article связи и
    подсвечивает именно cross-article пары. Направление — от/к A, id брать
    строго из входа.

    Результат -> кандидаты на INSERT в process_mining.entity_relations
    (только new <-> candidate).
    """
    types = ", ".join(f'"{t}"' for t in RELATION_TYPES)
    return f"""Ты — построитель графа знаний Process Mining.
Дан ОДИН новый узел A и список КАНДИДАТОВ B из существующего графа.
Оцени связь A с КАЖДЫМ кандидатом B по отдельности. Кандидаты уже отобраны
по семантической близости — но близость ≠ обязательно осмысленное ребро.

## НОВЫЙ УЗЕЛ A (id + текст):
{new_node_json}

## КАНДИДАТЫ B (id + текст) — каждого рассмотри отдельно:
{candidates_json}

## ПРАВИЛА:
1. Каждое ребро связывает ТОЛЬКО A с одним из B. Связи B<->B не строй.
   source_id/target_id — строго id из входа (A и один из B).
2. Направление важно (см. семантику). Ребро направленное source -> target.
3. relation_type выбирай РОВНО из словаря — изобретать ЗАПРЕЩЕНО:
   [{types}]
   Семантика:
   - relates_to     — общая тематическая связь (fallback, если нет точнее)
   - extends        — target развивает/расширяет source
   - based_on       — source построен на основе target
   - uses           — source использует target (метод/инструмент)
   - includes       — source включает target как часть
   - alternative_to — source и target — взаимозаменяемые альтернативы
   - describes      — source описывает target
   - evaluates      — source оценивает/тестирует target
   - determines     — source определяет/задаёт target
   - summarizes     — source суммирует target
4. Если для кандидата B осмысленной связи с A НЕТ — просто НЕ включай его.
   Не выдумывай ребро ради заполнения. Дубли одинаковых тем — это alternative_to
   или relates_to, а не пропуск.
5. relevance_score 0.0-1.0 — уверенность в связи. importance 0.0-1.0 — ценность
   для навигации по графу.
6. Один и тот же факт в A и B (та же концепция из разных статей) — валидная
   связь alternative_to / relates_to, обязательно её отрази.

## СТРОГО JSON (без markdown-обёртки):
{{
  "relations": [
    {{
      "source_id": 28,
      "target_id": 1,
      "relation_type": "alternative_to",
      "relevance_score": 0.9,
      "importance": 0.8,
      "reasoning": "Оба узла описывают OCPM из разных статей."
    }}
  ]
}}"""


# ============================================================
# 3. SYNTHESIZE — сборка wiki-страницы из группы узлов
# ============================================================
def build_wiki_synthesis_prompt(topic: str, nodes_json: str) -> str:
    """Синтез markdown-страницы из группы связанных узлов знания.

    Результат -> кандидат на INSERT/UPDATE в process_mining.wiki_pages.
    source_ids заполняются id узлов, из которых собрана страница.
    """
    return f"""Ты — редактор базы знаний Process Mining. Собери цельную wiki-страницу
из набора атомарных фактов по теме.

## ТЕМА СТРАНИЦЫ:
{topic}

## ИСХОДНЫЕ УЗЛЫ (id + текст) — единственный источник фактов:
{nodes_json}

## ПРАВИЛА СИНТЕЗА:
1. Пиши связный markdown: заголовок H1, логичные разделы H2, при нужде списки.
2. Факты БЕРИ ТОЛЬКО из переданных узлов. Ничего не выдумывай и не добавляй извне.
3. Убирай повторы, выстраивай факты в логичном порядке (общее -> частное).
4. Термины process mining и названия инструментов — в оригинале.
5. В конце ОБЯЗАТЕЛЬНО раздел "## Источники" со списком использованных узлов
   в формате "- knowledge #<id> — <короткая суть>".
6. index_entry — одна строка-аннотация страницы для оглавления (до 140 симв.).
7. В source_ids перечисли id ВСЕХ узлов, реально вошедших в текст.

## СТРОГО JSON (без markdown-обёртки; markdown только ВНУТРИ поля content_md):
{{
  "title": "Заголовок страницы",
  "content_md": "# Заголовок\\n\\n## Раздел\\nТекст...\\n\\n## Источники\\n- knowledge #22 — ...",
  "source_ids": [22, 23, 24],
  "index_entry": "Одна строка-аннотация страницы для оглавления.",
  "importance": 0.8
}}"""


# ============================================================
# 4. LINT — проверка качества узла/страницы (контроль базы)
# ============================================================
def build_knowledge_lint_prompt(item_type: str, item_json: str) -> str:
    """Проверка качества атома знания или wiki-страницы перед фиксацией.

    item_type: "knowledge" | "wiki_page".
    Вердикт lint управляет статусом: pass -> active, warn -> review,
    fail -> review c reason (кандидат в knowledge_review).
    """
    return f"""Ты — линтер качества базы знаний Process Mining.
Проверь объект типа "{item_type}" по критериям качества и вынеси вердикт.

## ПРОВЕРЯЕМЫЙ ОБЪЕКТ:
{item_json}

## КРИТЕРИИ (каждый true/false):
1. atomic        — факт самодостаточен (для knowledge) / страница цельная (для wiki_page)
2. grounded      — нет домыслов, всё опирается на факты, нет галлюцинаций
3. no_duplicate  — не выглядит как дубль тривиального/уже очевидного знания
4. clear         — сформулировано ясно, без мусора, местоимений-отсылок, обрывов
5. relevant_pm   — относится к Process Mining / смежной аналитике данных
6. well_formed   — для wiki_page: есть раздел "Источники" и структура; для knowledge: одна мысль

## ВЕРДИКТ:
- verdict = "pass" — все критичные критерии true, объект годен (status -> active)
- verdict = "warn" — есть мелкие замечания, но объект полезен (status -> review)
- verdict = "fail" — грубые нарушения, объект не годен (кандидат в knowledge_review)

## СТРОГО JSON (без markdown-обёртки):
{{
  "atomic": true,
  "grounded": true,
  "no_duplicate": true,
  "clear": true,
  "relevant_pm": true,
  "well_formed": true,
  "verdict": "pass",
  "reason": "Если warn/fail — кратко что не так. Если pass — пустая строка."
}}"""
